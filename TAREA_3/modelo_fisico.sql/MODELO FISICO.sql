BEGIN;

CREATE TABLE estudiante (
 id_estudiante INTEGER GENERATED BY DEFAULT AS IDENTITY,
 nombre VARCHAR(100) NOT NULL,
 email VARCHAR(150) NOT NULL,
 contrasena VARCHAR(255) NOT NULL,
 programa VARCHAR(100) NOT NULL,
 area_estudio VARCHAR(100),
 semestre SMALLINT,
 ciudad VARCHAR(100),
 biografia VARCHAR(500),
 foto_url VARCHAR(255),
 fecha_registro DATE NOT NULL DEFAULT CURRENT_DATE,
 fecha_actualizacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT pk_estudiante PRIMARY KEY (id_estudiante),
 CONSTRAINT uq_estudiante_email UNIQUE (email),
 CONSTRAINT ck_estudiante_semestre CHECK (semestre BETWEEN 1 AND 12)
);

CREATE TABLE habilidad (
 id_habilidad INTEGER GENERATED BY DEFAULT AS IDENTITY,
 nombre VARCHAR(100) NOT NULL,
 tipo VARCHAR(50) NOT NULL,
 CONSTRAINT pk_habilidad PRIMARY KEY (id_habilidad),
 CONSTRAINT uq_habilidad_nombre_tipo UNIQUE (nombre, tipo)
);

CREATE TABLE interes (
 id_interes INTEGER GENERATED BY DEFAULT AS IDENTITY,
 nombre VARCHAR(100) NOT NULL,
 CONSTRAINT pk_interes PRIMARY KEY (id_interes),
 CONSTRAINT uq_interes_nombre UNIQUE (nombre)
);

CREATE TABLE grupo (
 id_grupo INTEGER GENERATED BY DEFAULT AS IDENTITY,
 nombre VARCHAR(100) NOT NULL,
 descripcion VARCHAR(500),
 tipo VARCHAR(50) NOT NULL,
 fecha_creacion DATE NOT NULL DEFAULT CURRENT_DATE,
 CONSTRAINT pk_grupo PRIMARY KEY (id_grupo)
);

CREATE TABLE evento (
 id_evento INTEGER GENERATED BY DEFAULT AS IDENTITY,
 titulo VARCHAR(150) NOT NULL,
 descripcion VARCHAR(500),
 tipo VARCHAR(50) NOT NULL,
 fecha_hora TIMESTAMP NOT NULL,
 lugar VARCHAR(150),
 CONSTRAINT pk_evento PRIMARY KEY (id_evento)
);

CREATE TABLE publicacion (
 id_publicacion INTEGER GENERATED BY DEFAULT AS IDENTITY,
 contenido VARCHAR(1000) NOT NULL,
 tipo VARCHAR(30) NOT NULL,
 fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT pk_publicacion PRIMARY KEY (id_publicacion),
 CONSTRAINT ck_publicacion_tipo CHECK (tipo IN ('pregunta','recurso','noticia','meme','otro'))
);

CREATE TABLE estudiante_habilidad (
 id_estudiante INTEGER NOT NULL,
 id_habilidad INTEGER NOT NULL,
 nivel VARCHAR(30) NOT NULL,
 fecha_agregado DATE NOT NULL DEFAULT CURRENT_DATE,
 CONSTRAINT pk_estudiante_habilidad PRIMARY KEY (id_estudiante,id_habilidad),
 CONSTRAINT fk_esthab_estudiante FOREIGN KEY (id_estudiante) REFERENCES estudiante(id_estudiante) ON DELETE CASCADE ON UPDATE CASCADE,
 CONSTRAINT fk_esthab_habilidad FOREIGN KEY (id_habilidad) REFERENCES habilidad(id_habilidad) ON DELETE CASCADE ON UPDATE CASCADE,
 CONSTRAINT ck_esthab_nivel CHECK (nivel IN ('principiante','intermedio','avanzado'))
);

CREATE TABLE estudiante_interes (
 id_estudiante INTEGER NOT NULL,
 id_interes INTEGER NOT NULL,
 fecha_agregado DATE NOT NULL DEFAULT CURRENT_DATE,
 CONSTRAINT pk_estudiante_interes PRIMARY KEY (id_estudiante,id_interes),
 CONSTRAINT fk_estint_estudiante FOREIGN KEY (id_estudiante) REFERENCES estudiante(id_estudiante) ON DELETE CASCADE ON UPDATE CASCADE,
 CONSTRAINT fk_estint_interes FOREIGN KEY (id_interes) REFERENCES interes(id_interes) ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE estudiante_grupo (
 id_estudiante INTEGER NOT NULL,
 id_grupo INTEGER NOT NULL,
 rol VARCHAR(30) NOT NULL DEFAULT 'miembro',
 fecha_union DATE NOT NULL DEFAULT CURRENT_DATE,
 CONSTRAINT pk_estudiante_grupo PRIMARY KEY (id_estudiante,id_grupo),
 CONSTRAINT fk_estgrupo_estudiante FOREIGN KEY (id_estudiante) REFERENCES estudiante(id_estudiante) ON DELETE CASCADE ON UPDATE CASCADE,
 CONSTRAINT fk_estgrupo_grupo FOREIGN KEY (id_grupo) REFERENCES grupo(id_grupo) ON DELETE CASCADE ON UPDATE CASCADE,
 CONSTRAINT ck_estgrupo_rol CHECK (rol IN ('miembro','administrador'))
);

CREATE TABLE asistente_evento (
 id_estudiante INTEGER NOT NULL,
 id_evento INTEGER NOT NULL,
 estado VARCHAR(30) NOT NULL,
 fecha_registro DATE NOT NULL DEFAULT CURRENT_DATE,
 CONSTRAINT pk_asistente_evento PRIMARY KEY (id_estudiante,id_evento),
 CONSTRAINT fk_asisev_estudiante FOREIGN KEY (id_estudiante) REFERENCES estudiante(id_estudiante) ON DELETE CASCADE ON UPDATE CASCADE,
 CONSTRAINT fk_asisev_evento FOREIGN KEY (id_evento) REFERENCES evento(id_evento) ON DELETE CASCADE ON UPDATE CASCADE,
 CONSTRAINT ck_asisev_estado CHECK (estado IN ('organizador','invitado','asistente'))
);

CREATE TABLE publicacion_estudiante (
 id_publicacion INTEGER NOT NULL,
 id_estudiante INTEGER NOT NULL,
 rol_autor VARCHAR(30) NOT NULL DEFAULT 'autor principal',
 fecha_autoria TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT pk_publicacion_estudiante PRIMARY KEY (id_publicacion,id_estudiante),
 CONSTRAINT fk_pubest_publicacion FOREIGN KEY (id_publicacion) REFERENCES publicacion(id_publicacion) ON DELETE CASCADE ON UPDATE CASCADE,
 CONSTRAINT fk_pubest_estudiante FOREIGN KEY (id_estudiante) REFERENCES estudiante(id_estudiante) ON DELETE CASCADE ON UPDATE CASCADE,
 CONSTRAINT ck_pubest_rol CHECK (rol_autor IN ('autor principal','coautor'))
);

CREATE TABLE comentario (
 id_comentario INTEGER GENERATED BY DEFAULT AS IDENTITY,
 id_publicacion INTEGER NOT NULL,
 id_estudiante INTEGER NOT NULL,
 texto VARCHAR(500) NOT NULL,
 fecha_comentario TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT pk_comentario PRIMARY KEY (id_comentario),
 CONSTRAINT fk_comentario_publicacion FOREIGN KEY (id_publicacion) REFERENCES publicacion(id_publicacion) ON DELETE CASCADE ON UPDATE CASCADE,
 CONSTRAINT fk_comentario_estudiante FOREIGN KEY (id_estudiante) REFERENCES estudiante(id_estudiante) ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE reaccion (
 id_publicacion INTEGER NOT NULL,
 id_estudiante INTEGER NOT NULL,
 tipo_reaccion VARCHAR(20) NOT NULL,
 fecha_reaccion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT pk_reaccion PRIMARY KEY (id_publicacion,id_estudiante),
 CONSTRAINT fk_reaccion_publicacion FOREIGN KEY (id_publicacion) REFERENCES publicacion(id_publicacion) ON DELETE CASCADE ON UPDATE CASCADE,
 CONSTRAINT fk_reaccion_estudiante FOREIGN KEY (id_estudiante) REFERENCES estudiante(id_estudiante) ON DELETE CASCADE ON UPDATE CASCADE,
 CONSTRAINT ck_reaccion_tipo CHECK (tipo_reaccion IN ('me gusta','me encanta','apoyo','interesante'))
);

CREATE TABLE seguir (
 id_seguidor INTEGER NOT NULL,
 id_seguido INTEGER NOT NULL,
 fecha_seguimiento DATE NOT NULL DEFAULT CURRENT_DATE,
 CONSTRAINT pk_seguir PRIMARY KEY (id_seguidor,id_seguido),
 CONSTRAINT fk_seguir_seguidor FOREIGN KEY (id_seguidor) REFERENCES estudiante(id_estudiante) ON DELETE CASCADE ON UPDATE CASCADE,
 CONSTRAINT fk_seguir_seguido FOREIGN KEY (id_seguido) REFERENCES estudiante(id_estudiante) ON DELETE CASCADE ON UPDATE CASCADE,
 CONSTRAINT ck_seguir_no_autoseguimiento CHECK (id_seguidor <> id_seguido)
);

CREATE TABLE mentoria (
 id_mentor INTEGER NOT NULL,
 id_aprendiz INTEGER NOT NULL,
 id_habilidad INTEGER NOT NULL,
 estado VARCHAR(30) NOT NULL DEFAULT 'en proceso',
 fecha_inicio DATE NOT NULL DEFAULT CURRENT_DATE,
 CONSTRAINT pk_mentoria PRIMARY KEY (id_mentor,id_aprendiz,id_habilidad),
 CONSTRAINT fk_mentoria_mentor FOREIGN KEY (id_mentor) REFERENCES estudiante(id_estudiante) ON DELETE CASCADE ON UPDATE CASCADE,
 CONSTRAINT fk_mentoria_aprendiz FOREIGN KEY (id_aprendiz) REFERENCES estudiante(id_estudiante) ON DELETE CASCADE ON UPDATE CASCADE,
 CONSTRAINT fk_mentoria_habilidad FOREIGN KEY (id_habilidad) REFERENCES habilidad(id_habilidad) ON DELETE RESTRICT ON UPDATE CASCADE,
 CONSTRAINT ck_mentoria_no_automentoria CHECK (id_mentor <> id_aprendiz),
 CONSTRAINT ck_mentoria_estado CHECK (estado IN ('en proceso','completada','cancelada'))
);

COMMIT;